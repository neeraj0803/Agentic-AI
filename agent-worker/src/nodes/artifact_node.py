import datetime
import json
import logging
from pathlib import Path
import re
from typing import Any, Callable

from openai import AzureOpenAI

from ..config import ROOT_DIR, get_artifacts_dir, get_llm_config_path

logger = logging.getLogger(__name__)


def load_llm_config(config_path: Path | None = None) -> dict[str, Any]:
    target = config_path or get_llm_config_path()
    if target.exists():
        try:
            with target.open("r", encoding="utf-8") as f:
                return json.load(f)
        except Exception as exc:
            logger.warning("Failed to load LLM config from %s: %s", target, exc)
    return {}


def _collect_upstream_data(state: dict[str, Any], current_node_id: str) -> dict[str, Any]:
    """Dynamically collects all outputs and content generated by upstream nodes without hardcoding schemas."""
    collected: dict[str, Any] = {}

    for node in state.get("nodes", []):
        nid = node.get("node_id") or node.get("id")
        if nid and nid != current_node_id and node.get("output"):
            collected[f"{nid}_output"] = node.get("output")

    for key in ["drafted_tests", "context_brief", "skills", "validated_inputs", "input_context"]:
        val = state.get(key)
        if val:
            collected[key] = val

    for k, v in state.items():
        if k.endswith("_output") and k != f"{current_node_id}_output" and k not in collected:
            collected[k] = v

    return collected


def _generic_dict_to_markdown(data: Any, level: int = 1) -> str:
    """Dynamically serializes any arbitrary Python data structure into clean, human-readable Markdown."""
    lines: list[str] = []
    prefix = "#" * min(level, 6)

    if isinstance(data, str):
        return data

    if isinstance(data, list):
        for idx, item in enumerate(data):
            if isinstance(item, dict):
                lines.append(f"\n{prefix}# Item {idx + 1}")
                lines.append(_generic_dict_to_markdown(item, level + 2))
            else:
                lines.append(f"- {item}")
        return "\n".join(lines)

    if isinstance(data, dict):
        for key, value in data.items():
            formatted_key = key.replace("_", " ").title()
            if isinstance(value, (dict, list)):
                lines.append(f"\n{prefix}# {formatted_key}")
                lines.append(_generic_dict_to_markdown(value, level + 2))
            else:
                lines.append(f"- **{formatted_key}:** {value}")
        return "\n".join(lines)

    return str(data)


def _generate_markdown_artifact_via_llm(
    upstream_data: dict[str, Any],
    metadata: dict[str, Any],
    custom_system_prompt: str | None = None,
    custom_user_prompt: str | None = None,
    config_path: Path | None = None,
) -> tuple[str, str]:
    """Uses Azure OpenAI to transform upstream execution outputs into a polished Markdown document."""
    llm_cfg = load_llm_config(config_path)
    api_details = llm_cfg.get("apiDetails", {})
    api_key = api_details.get("apiKey")
    api_version = api_details.get("apiVersion", "2025-01-01-preview")
    base_url = api_details.get("baseURL")
    deployment_name = api_details.get("deploymentName", "gpt-4o-mini-developers")

    if not api_key or not base_url:
        return _build_fallback_markdown(upstream_data, metadata), "structural_serializer (no credentials)"

    system_msg = (
        custom_system_prompt
        or "You are an expert Technical Documentation and QE Artifact Synthesis Agent.\n"
        "Your task is to take the accumulated workflow data, test package details, and architectural signals, "
        "and synthesize a comprehensive, clean, beautifully-structured Markdown (.md) document.\n\n"
        "Guidelines:\n"
        "- Generate standard Markdown only. Do not wrap the response in markdown code blocks unless requested.\n"
        "- Include an Executive Summary, Acceptance Criteria Traceability, Complete Test Cases (with tables or step lists), "
        "Regression Scope, and Risk Mitigations.\n"
        "- Use clean formatting: headers (#, ##, ###), bullet lists, bold text, and markdown tables where appropriate."
    )

    story_id = metadata.get("story_id", "Workflow-Artifact")
    data_summary = json.dumps(upstream_data, indent=2, default=str)

    user_msg = (
        custom_user_prompt
        or f"Workflow Metadata:\n{json.dumps(metadata, indent=2)}\n\n"
        f"Upstream Node Outputs and Context:\n{data_summary}\n\n"
        f"Generate the comprehensive Markdown artifact for {story_id}:"
    )

    try:
        client = AzureOpenAI(
            api_key=api_key,
            api_version=api_version,
            azure_endpoint=base_url,
        )
        response = client.chat.completions.create(
            model=deployment_name,
            messages=[
                {"role": "system", "content": system_msg},
                {"role": "user", "content": user_msg},
            ],
            temperature=0.2,
        )

        raw_content = response.choices[0].message.content or ""
        cleaned = raw_content.strip()
        if cleaned.startswith("```markdown") and cleaned.endswith("```"):
            cleaned = cleaned[len("```markdown"): -3].strip()
        elif cleaned.startswith("```md") and cleaned.endswith("```"):
            cleaned = cleaned[len("```md"): -3].strip()
        elif cleaned.startswith("```") and cleaned.endswith("```"):
            cleaned = cleaned[3:-3].strip()

        logger.info("Successfully generated Markdown artifact via LLM deployment %s", deployment_name)
        return cleaned, "azure_openai"
    except Exception as exc:
        logger.warning("LLM call for artifact creation failed or offline (%s). Using dynamic structural fallback.", exc)
        return _build_fallback_markdown(upstream_data, metadata), f"fallback_error: {exc}"


def _build_fallback_markdown(upstream_data: dict[str, Any], metadata: dict[str, Any]) -> str:
    """Builds a structured, human-readable Markdown document dynamically from any data."""
    story_id = metadata.get("story_id", "Workflow-Artifact")
    workflow_id = metadata.get("workflow_id", "Agent-Workflow")
    generated_at = metadata.get("generated_at", datetime.datetime.now(datetime.timezone.utc).isoformat())

    lines = [
        f"# {story_id} - Generated Workflow Artifact",
        "",
        f"> **Workflow:** `{workflow_id}`  ",
        f"> **Generated At:** `{generated_at}`  ",
        f"> **Session ID:** `{metadata.get('workflow_session_id', 'N/A')}`",
        "",
        "---",
        "",
    ]

    for section_key, section_data in upstream_data.items():
        title = section_key.replace("_", " ").title()
        lines.append(f"## {title}\n")
        lines.append(_generic_dict_to_markdown(section_data, level=3))
        lines.append("")

    return "\n".join(lines)


def create_artifact_node(
    node_def: dict[str, Any], workflow_spec: dict[str, Any]
) -> Callable[[dict[str, Any]], dict[str, Any]]:
    """Factory creating a dynamic Markdown artifact generator node."""
    node_id = node_def.get("id") or node_def.get("node_id") or "prepare_test_package_artifacts"
    custom_dir_str = (
        node_def.get("folder")
        or node_def.get("artifact_dir")
        or node_def.get("output_dir")
        or node_def.get("artefact_dir")
    )
    if custom_dir_str:
        artifact_dir = Path(custom_dir_str) if Path(custom_dir_str).is_absolute() else ROOT_DIR / custom_dir_str
    else:
        artifact_dir = get_artifacts_dir()

    custom_filename_template = (
        node_def.get("filename")
        or node_def.get("artifact_filename")
        or node_def.get("file_name")
    )
    use_llm = node_def.get("use_llm", True)
    custom_system_prompt = node_def.get("system_message") or node_def.get("system_prompt")
    custom_user_prompt = node_def.get("user_prompt") or node_def.get("prompt")
    custom_config_path = Path(node_def["llm_config_path"]) if "llm_config_path" in node_def else None

    def artifact_node(state: dict[str, Any]) -> dict[str, Any]:
        state["status"] = "running"
        state["current_node"] = node_id

        # 1. Resolve Story and Reference ID dynamically
        validated_inputs = state.get("validated_inputs", {})
        story_id = (
            node_def.get("story_id")
            or validated_inputs.get("jira_story_or_epic_id")
            or state.get("story_id")
            or "CHK-100"
        )
        timestamp_str = datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%dT%H%M%SZ")

        # 2. Dynamically collect all upstream generated data without hardcoded keys
        upstream_data = _collect_upstream_data(state, node_id)

        metadata = {
            "story_id": story_id,
            "node_id": node_id,
            "workflow_id": state.get("workflow_id", "QE-201-draft-test-cases-from-jira"),
            "workflow_session_id": state.get("workflow_session_id", "N/A"),
            "generated_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        }

        # 3. Generate Markdown content
        engine_used = "dynamic_serializer"
        if use_llm:
            markdown_content, engine_used = _generate_markdown_artifact_via_llm(
                upstream_data=upstream_data,
                metadata=metadata,
                custom_system_prompt=custom_system_prompt,
                custom_user_prompt=custom_user_prompt,
                config_path=custom_config_path,
            )
        else:
            markdown_content = _build_fallback_markdown(upstream_data, metadata)

        # 4. Determine target file path (ensuring .md extension)
        if custom_filename_template:
            fname = custom_filename_template.format(
                story_id=story_id,
                node_id=node_id,
                timestamp=timestamp_str,
            )
            if not fname.endswith(".md"):
                fname = re.sub(r"\.[^.]+$", "", fname) + ".md"
        else:
            fname = f"{story_id}_artifact.md"

        artifact_dir.mkdir(parents=True, exist_ok=True)
        target_file = artifact_dir / fname

        # 5. Write the Markdown (.md) artifact file to disk
        try:
            with target_file.open("w", encoding="utf-8") as f:
                f.write(markdown_content)
            file_size = target_file.stat().st_size
            logger.info("Successfully created Markdown artifact at %s (%d bytes)", target_file, file_size)
        except Exception as exc:
            logger.error("Failed to write Markdown artifact file to %s: %s", target_file, exc)
            file_size = 0

        # 6. Save artifact references into state
        artifact_record = {
            "artifact_file": target_file.name,
            "artifact_path": str(target_file),
            "format": "markdown",
            "file_size_bytes": file_size,
            "engine": engine_used,
            "metadata": metadata,
            "content": markdown_content,
        }
        state["artifacts"] = artifact_record
        state["artifact_path"] = str(target_file)
        state["artifact_file"] = target_file.name
        state["artifact_content"] = markdown_content

        node_output = {
            "status": "completed",
            "node_id": node_id,
            "story_id": story_id,
            "artifact_folder": str(artifact_dir),
            "artifact_file": target_file.name,
            "artifact_path": str(target_file),
            "file_size_bytes": file_size,
            "engine": engine_used,
            "summary": f"Created Markdown artifact in '{artifact_dir.name}/{target_file.name}' ({file_size} bytes via {engine_used}).",
        }

        if "nodes" not in state or not isinstance(state["nodes"], list):
            state["nodes"] = []

        found = False
        for item in state.get("nodes", []):
            if item.get("node_id") == node_id or item.get("id") == node_id:
                item["output"] = node_output
                item["status"] = "completed"
                found = True
                break
        if not found:
            state["nodes"].append({
                "id": node_id,
                "node_id": node_id,
                "node_name": str(node_id).replace("_", " ").title(),
                "node_type": "agent",
                "output": node_output,
                "status": "completed",
            })

        return state


    return artifact_node

